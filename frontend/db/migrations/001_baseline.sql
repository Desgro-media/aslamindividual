-- Baseline schema — the exact tables the Spring Boot backend (Hibernate
-- ddl-auto=update) used to create and maintain on its own.
--
-- Everything here is idempotent:
--   * On a brand-new database it creates the whole schema.
--   * On a database that the old Java backend already populated it is a
--     no-op, apart from the handful of drift fixes at the bottom (legacy
--     NOT NULL constraints that Hibernate never relaxed).
--
-- Column names/types intentionally mirror Hibernate's naming
-- (camelCase -> snake_case) so an existing database can be pointed at the
-- new backend with `pg_dump | psql` and nothing else.

CREATE TABLE IF NOT EXISTS app_user (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bio                    text,
    bookable               boolean NOT NULL DEFAULT true,
    created_at             timestamp(6) without time zone,
    job_title              varchar(255),
    name                   varchar(255),
    password               varchar(255) NOT NULL,
    profile_image_url      text,
    role                   varchar(255) NOT NULL,
    slug                   varchar(255) UNIQUE,
    updated_at             timestamp(6) without time zone,
    username               varchar(255) NOT NULL UNIQUE,
    account_type           varchar(255) CHECK (account_type IN ('INDIVIDUAL', 'CLINIC')),
    permissions            text,
    tenant_id              bigint,
    enabled                boolean NOT NULL DEFAULT true,
    phone                  varchar(255),
    credentials_changed_at timestamp(6) without time zone
);

