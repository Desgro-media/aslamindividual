-- ── Drift fixes for databases created by older Hibernate versions ────────────
-- A whole-day date override has no slot time; older schemas made the column
-- NOT NULL and Hibernate never relaxes a constraint.
ALTER TABLE doctor_date_override ALTER COLUMN slot_time DROP NOT NULL;

-- Legacy single price/offered columns on doctor_service_price (superseded by
-- the per-mode columns). Still present on old databases, and NOT NULL there —
-- relax them so new rows (which never set them) can be inserted.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'doctor_service_price' AND column_name = 'price') THEN
        ALTER TABLE doctor_service_price ALTER COLUMN price DROP NOT NULL;
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'doctor_service_price' AND column_name = 'offered') THEN
        ALTER TABLE doctor_service_price ALTER COLUMN offered DROP NOT NULL;
    END IF;
END $$;

-- ── Idempotent one-time backfills the Java StartupInitializer ran every boot ─
UPDATE appointment SET assigned_doctor_id = psychologist_id WHERE assigned_doctor_id IS NULL;
UPDATE appointment SET mode = 'OFFLINE' WHERE mode IS NULL;
UPDATE doctor_availability_block SET mode = 'OFFLINE' WHERE mode IS NULL;
UPDATE doctor_weekly_slot SET mode = 'OFFLINE' WHERE mode IS NULL;
UPDATE doctor_date_override SET mode = 'OFFLINE' WHERE mode IS NULL AND slot_time IS NOT NULL;

