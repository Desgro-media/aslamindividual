-- Client sharing: a therapist (or the clinic owner) can share a client with
-- another therapist in the same clinic, who can then follow and edit that
-- client's journey (session status, follow-ups, session notes, wrap-ups).
--
-- Purely additive. A row means "shared_with_id has access to patient_id"; the
-- clinic owner already has access to every client and is never stored here.

CREATE TABLE IF NOT EXISTS patient_share (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    psychologist_id bigint NOT NULL,                                          -- the clinic (tenant)
    patient_id      bigint NOT NULL REFERENCES patient (id)  ON DELETE CASCADE,
    shared_with_id  bigint NOT NULL REFERENCES app_user (id) ON DELETE CASCADE, -- the therapist who gains access
    shared_by       bigint,                                                   -- who shared it (kept even if that account is later removed)
    created_at      timestamp(6) without time zone,
    CONSTRAINT uq_patient_share UNIQUE (patient_id, shared_with_id)
);
CREATE INDEX IF NOT EXISTS idx_patient_share_with ON patient_share (shared_with_id);
CREATE INDEX IF NOT EXISTS idx_patient_share_tenant ON patient_share (psychologist_id);
